// Usage:
//   deno run -A supabase/scripts/build_airports_seed.ts supabase/seed/airports.csv > supabase/migrations/20261028000002_airports_seed.sql
//
// Input is the filtered OurAirports CSV (scheduled_service = yes, 4-letter ident) with the
// original columns. OurAirports has no timezone column, so tz is derived from the
// coordinates with geo-tz.
// To refresh the input from the full dataset, run with --filter:
//   deno run -A supabase/scripts/build_airports_seed.ts --filter airports_full.csv > supabase/seed/airports.csv
import { find } from "npm:geo-tz@8.1.2";

function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}

function csvLine(cells: string[]): string {
  return cells.map((c) => /[",\n\r]/.test(c) ? `"${c.replaceAll('"', '""')}"` : c).join(",");
}

const sql = (s: string | null | undefined) =>
  s === null || s === undefined || s === "" ? "null" : `'${s.replaceAll("'", "''")}'`;

const args = Deno.args;
if (args[0] === "--filter") {
  const rows = parseCsv(await Deno.readTextFile(args[1]));
  const h = rows[0];
  const ix = (n: string) => h.indexOf(n);
  const out = [csvLine(h)];
  for (const r of rows.slice(1)) {
    if (r[ix("scheduled_service")] === "yes" && /^[A-Z]{4}$/.test(r[ix("ident")])) out.push(csvLine(r));
  }
  console.log(out.join("\n"));
  Deno.exit(0);
}

const rows = parseCsv(await Deno.readTextFile(args[0]));
const h = rows[0];
const col = (r: string[], n: string) => r[h.indexOf(n)];

const seen = new Set<string>();
const seenIata = new Set<string>();
const values: string[] = [];
for (const r of rows.slice(1)) {
  const icao = col(r, "ident");
  if (col(r, "scheduled_service") !== "yes" || !/^[A-Z]{4}$/.test(icao) || seen.has(icao)) continue;
  const lat = Number(col(r, "latitude_deg"));
  const lon = Number(col(r, "longitude_deg"));
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  seen.add(icao);
  let iata: string | null = col(r, "iata_code") || null;
  if (iata && seenIata.has(iata)) iata = null;
  if (iata) seenIata.add(iata);
  const tz = find(lat, lon)[0] ?? null;
  values.push(
    `(${sql(icao)}, ${sql(iata)}, ${sql(col(r, "name"))}, ${sql(col(r, "municipality"))}, ${sql(col(r, "iso_country"))}, ${lat}, ${lon}, ${sql(tz)})`,
  );
}

console.log("-- Generated by supabase/scripts/build_airports_seed.ts from supabase/seed/airports.csv. Do not edit.");
console.log("insert into airports (icao, iata, name, city, country, lat, lon, tz) values");
console.log(values.join(",\n"));
console.log("on conflict (icao) do nothing;");
