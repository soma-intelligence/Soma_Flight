#!/usr/bin/env python3
"""Writes Resources/Licenses/third-party.txt: the licence texts of everything linked into the app.

    python3 -I Scripts/licenses/build_third_party.py

Swift packages: every identity in Packages/FlightKit/Package.resolved, with the LICENSE and NOTICE
files copied verbatim from Packages/FlightKit/.build/checkouts (run `swift package resolve` first).
Rust crates: the normal dependency tree of flightcore-ffi (`cargo tree -p flightcore-ffi -e normal`),
with each crate's LICENSE, COPYING and NOTICE files copied verbatim from the cargo registry. A crate
that ships no licence file gets the standard text of its SPDX licence from a crate that does.
Identical texts are printed once with every package that carries them.
Blocks are separated by a line of eight percent signs, which AcknowledgementsView splits on.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KIT = ROOT / "Packages/FlightKit"
OUT = KIT / "Sources/FlightKit/Resources/Licenses/third-party.txt"
SEP = "%" * 8
KEYS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")
# Crates without a licence file (uniffi, MPL-2.0) take the text from a crate that ships it verbatim.
FALLBACK = {"MPL-2.0": "uluru"}


def licence_files(directory: Path) -> list[Path]:
    return sorted(p for p in directory.iterdir()
                  if p.is_file() and p.name.upper().startswith(KEYS) and not p.name.endswith((".rs", ".toml")))


def swift_packages() -> list[tuple[str, str, list[Path]]]:
    pins = json.loads((KIT / "Package.resolved").read_text())["pins"]
    out = []
    for pin in pins:
        name = pin["identity"]
        files = licence_files(KIT / ".build/checkouts" / name)
        if not files:
            sys.exit(f"no licence file for {name}; run swift package resolve")
        out.append((name, pin["state"]["version"], files))
    return out


def registry_dir(name: str, version: str) -> Path:
    for base in sorted((Path.home() / ".cargo/registry/src").glob("*")):
        d = base / f"{name}-{version}"
        if d.is_dir():
            return d
    sys.exit(f"{name} {version} is not in the cargo registry; run cargo fetch")


def rust_crates() -> list[tuple[str, str, str, list[Path]]]:
    text = subprocess.run(["cargo", "tree", "-p", "flightcore-ffi", "-e", "normal", "--prefix", "none",
                           "--format", "{p}|{l}", "--offline"], cwd=ROOT / "core", check=True,
                          capture_output=True, text=True).stdout
    seen = {}
    for line in text.splitlines():
        m = re.match(r"(\S+) v(\S+)(?: \(proc-macro\))?(?: \(([^)]*)\))?\|(.*)$", line)
        if not m or (m.group(3) and m.group(3) != "*" and m.group(3).startswith("/")):
            continue  # a workspace crate
        seen[(m.group(1), m.group(2))] = m.group(4).replace(" (*)", "").strip()
    out = []
    for (name, version), spdx in sorted(seen.items()):
        out.append((name, version, spdx, licence_files(registry_dir(name, version))))
    return out


def main() -> int:
    blocks: dict[str, list[str]] = {}
    order: list[str] = []

    def add(label: str, files: list[Path]) -> None:
        for f in files:
            body = f.read_text(encoding="utf-8").strip("\n")
            if body not in blocks:
                blocks[body] = []
                order.append(body)
            blocks[body].append(f"{label} ({f.name})")

    packages = []
    for name, version, files in swift_packages():
        packages.append(name)
        add(f"{name} {version}", files)
    crates = []
    for name, version, spdx, files in rust_crates():
        crates.append(name)
        if not files:
            donor = next((d for s, d in FALLBACK.items() if s in spdx), None)
            if donor is None:
                sys.exit(f"{name} has no licence file and no fallback for {spdx}")
            donor_dir = next(p for base in (Path.home() / ".cargo/registry/src").glob("*")
                             for p in sorted(base.glob(f"{donor}-*")) if p.is_dir())
            files = licence_files(donor_dir)
            label = f"{name} {version} ({spdx}, standard text)"
        else:
            label = f"{name} {version}"
        add(label, files)

    parts = ["Soma Flight is built with the open source software below. Each licence text is copied "
             "unchanged from the package it comes with. Generated by Scripts/licenses/build_third_party.py.\n\n"
             "Swift packages: " + ", ".join(packages) + ".\n"
             f"Rust crates in the flight engine ({len(set(crates))}): " + ", ".join(sorted(set(crates))) + "."]
    for body in order:
        parts.append("Applies to: " + "; ".join(blocks[body]) + "\n\n" + body)
    OUT.write_text(f"\n{SEP}\n".join(parts) + "\n", encoding="utf-8")
    print(f"{len(packages)} Swift packages, {len(set(crates))} crates, {len(order)} distinct texts, "
          f"{OUT.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
